package com.homingsms.core.telephony

import com.homingsms.core.model.ErrorCodes

object SmsResults {
    const val RESULT_ERROR_GENERIC_FAILURE = 1
    const val RESULT_ERROR_RADIO_OFF = 2
    const val RESULT_ERROR_NULL_PDU = 3
    const val RESULT_ERROR_NO_SERVICE = 4
    const val RESULT_ERROR_LIMIT_EXCEEDED = 5
    const val RESULT_ERROR_FDN_CHECK_FAILURE = 6
    const val RESULT_ERROR_SHORT_CODE_NOT_ALLOWED = 7
    const val RESULT_ERROR_SHORT_CODE_NEVER_ALLOWED = 8
    const val RESULT_RADIO_NOT_AVAILABLE = 9
    const val RESULT_NETWORK_REJECT = 10
    const val RESULT_UNEXPECTED_EVENT_STOP_SENDING = 30
    const val RESULT_RIL_RADIO_NOT_AVAILABLE = 100
    const val RESULT_RIL_REQUEST_RATE_LIMITED = 110

    private val names = mapOf(
        RESULT_ERROR_GENERIC_FAILURE to "RESULT_ERROR_GENERIC_FAILURE",
        RESULT_ERROR_RADIO_OFF to "RESULT_ERROR_RADIO_OFF",
        RESULT_ERROR_NULL_PDU to "RESULT_ERROR_NULL_PDU",
        RESULT_ERROR_NO_SERVICE to "RESULT_ERROR_NO_SERVICE",
        RESULT_ERROR_LIMIT_EXCEEDED to "RESULT_ERROR_LIMIT_EXCEEDED",
        RESULT_ERROR_FDN_CHECK_FAILURE to "RESULT_ERROR_FDN_CHECK_FAILURE",
        RESULT_ERROR_SHORT_CODE_NOT_ALLOWED to "RESULT_ERROR_SHORT_CODE_NOT_ALLOWED",
        RESULT_ERROR_SHORT_CODE_NEVER_ALLOWED to "RESULT_ERROR_SHORT_CODE_NEVER_ALLOWED",
        RESULT_RADIO_NOT_AVAILABLE to "RESULT_RADIO_NOT_AVAILABLE",
        RESULT_NETWORK_REJECT to "RESULT_NETWORK_REJECT",
        RESULT_UNEXPECTED_EVENT_STOP_SENDING to "RESULT_UNEXPECTED_EVENT_STOP_SENDING",
        RESULT_RIL_RADIO_NOT_AVAILABLE to "RESULT_RIL_RADIO_NOT_AVAILABLE",
        RESULT_RIL_REQUEST_RATE_LIMITED to "RESULT_RIL_REQUEST_RATE_LIMITED"
    )

    fun errorCode(resultCode: Int): String = when (resultCode) {
        RESULT_ERROR_RADIO_OFF, RESULT_RADIO_NOT_AVAILABLE, RESULT_RIL_RADIO_NOT_AVAILABLE -> ErrorCodes.RADIO_OFF
        RESULT_ERROR_NULL_PDU -> ErrorCodes.NULL_PDU
        RESULT_ERROR_NO_SERVICE -> ErrorCodes.NO_SERVICE
        RESULT_ERROR_LIMIT_EXCEEDED, RESULT_UNEXPECTED_EVENT_STOP_SENDING, RESULT_RIL_REQUEST_RATE_LIMITED -> ErrorCodes.SMS_LIMIT_REACHED
        RESULT_ERROR_SHORT_CODE_NOT_ALLOWED, RESULT_ERROR_SHORT_CODE_NEVER_ALLOWED -> ErrorCodes.SHORT_CODE_NOT_ALLOWED
        else -> ErrorCodes.GENERIC_FAILURE
    }

    fun isLimitHit(resultCode: Int): Boolean = errorCode(resultCode) == ErrorCodes.SMS_LIMIT_REACHED

    fun describe(resultCode: Int): String = names[resultCode]?.let { "$it ($resultCode)" } ?: "Send result code $resultCode"

    fun error(resultCode: Int): String = ErrorCodes.encode(errorCode(resultCode), "Send result: ${describe(resultCode)}")
}
